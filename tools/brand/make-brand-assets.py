#!/usr/bin/env python3
"""Renders every platform's icon and listing artwork from Reflux's master brand geometry (design/brand/README.md).

    python -I tools/brand/make-brand-assets.py

Reads design/brand/reflux-mark.svg and reflux-lockup.svg (polygons: absolute M/L/Z, even-odd), and writes:

  desktop/app/packaging/reflux.png, reflux.ico          the desktop app icon (Linux 512 px; Windows 16 to 256 px)
  android/app/src/main/res/drawable/ic_launcher_foreground.xml, ic_launcher_monochrome.xml   adaptive icon layers
  android/app/src/main/res/drawable-xhdpi/tv_banner.png the Android TV / Fire TV launcher banner (320 x 180)
  desktop/app/src/main/resources/reflux-mark.path      the mark's path data, for the window icon (Main.kt)
  website/public/                                       favicon.svg, favicon-32.png, apple-touch-icon.png,
                                                        icon-192.png, icon-512.png, og-image.png, mark.svg, lockup.svg
  design/brand/store/                                   Google Play and Amazon Appstore listing artwork

Needs Pillow. Rendering is supersampled 4x and reduced with a box filter, so the same inputs give the same pixels.
"""
import pathlib
import re
import struct

from PIL import Image, ImageChops, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[2]
BRAND = ROOT / "design" / "brand"
INK = (0xF5, 0xF5, 0xF6)
TOP, BOTTOM = (0x2C, 0x2C, 0x33), (0x0D, 0x0D, 0x10)
SS = 4


def rings(svg: pathlib.Path):
    text = svg.read_text(encoding="utf-8")
    view = [float(v) for v in re.search(r'viewBox="([^"]+)"', text).group(1).split()]
    data = re.search(r' d="([^"]+)"', text).group(1)
    out = []
    for ring in data.split("Z"):
        nums = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", ring)]
        if len(nums) >= 6:
            out.append(list(zip(nums[0::2], nums[1::2])))
    return view, data, out


MARK_VIEW, MARK_DATA, MARK = rings(BRAND / "reflux-mark.svg")
LOCK_VIEW, LOCK_DATA, LOCK = rings(BRAND / "reflux-lockup.svg")


def coverage(shape, size, box):
    """An L-mode mask of [shape] (rings in a view), fitted into [box] = (x, y, w, h) of an image [size], even-odd."""
    view, polys = shape
    w, h = size[0] * SS, size[1] * SS
    bx, by, bw, bh = (v * SS for v in box)
    scale = min(bw / view[2], bh / view[3])
    ox = bx + (bw - view[2] * scale) / 2 - view[0] * scale
    oy = by + (bh - view[3] * scale) / 2 - view[1] * scale
    mask = Image.new("L", (w, h), 0)
    for ring in polys:
        layer = Image.new("L", (w, h), 0)
        ImageDraw.Draw(layer).polygon([(ox + x * scale, oy + y * scale) for x, y in ring], fill=255)
        mask = ImageChops.difference(mask, layer)
    return mask.resize(size, Image.Resampling.BOX)


def ground(size, radius=0.0):
    """Graphite lit from the top left, as the interface's materials are; [radius] rounds the corners (share of side)."""
    w, h = size
    img = Image.new("RGBA", size)
    px = img.load()
    for y in range(h):
        for x in range(w):
            t = min(1.0, (0.35 * x / w + 0.65 * y / h) / 0.75)
            px[x, y] = tuple(round(TOP[i] + (BOTTOM[i] - TOP[i]) * t) for i in range(3)) + (255,)
    if radius:
        corner = Image.new("L", (w * SS, h * SS), 0)
        ImageDraw.Draw(corner).rounded_rectangle((0, 0, w * SS - 1, h * SS - 1), radius=radius * min(w, h) * SS, fill=255)
        img.putalpha(corner.resize(size, Image.Resampling.BOX))
    return img


def ink(img, mask):
    layer = Image.new("RGBA", img.size, INK + (255,))
    img.paste(layer, (0, 0), mask)
    return img


def tile(px, radius=0.0, share=0.66):
    """The app icon: the mark on graphite, [share] of the side wide."""
    m = (1 - share) / 2 * px
    return ink(ground((px, px), radius), coverage((MARK_VIEW, MARK), (px, px), (m, m, px - 2 * m, px - 2 * m)))


def banner(size, share):
    """The lockup centred on graphite, [share] of the width."""
    w, h = size
    bw = w * share
    return ink(ground(size), coverage((LOCK_VIEW, LOCK), size, ((w - bw) / 2, 0, bw, h)))


def ico(images):
    entries, data = [], b""
    offset = 6 + 16 * len(images)
    for img in images:
        import io
        buf = io.BytesIO(); img.save(buf, "PNG"); png = buf.getvalue()
        s = img.size[0]
        entries.append(struct.pack("<BBBBHHII", s % 256, s % 256, 0, 0, 1, 32, len(png), offset + len(data)))
        data += png
    return struct.pack("<HHH", 0, 1, len(images)) + b"".join(entries) + data


def vector(fill, comment):
    """The adaptive icon's foreground: the mark in the 66 dp safe zone of a 108 dp layer, 56 dp wide."""
    scale = 56 / MARK_VIEW[2]
    off = 54 - 50 * scale
    path = " ".join("M" + " L".join("%.2f,%.2f" % (off + x * scale, off + y * scale) for x, y in ring) + " Z" for ring in MARK)
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- %s Generated by tools/brand/make-brand-assets.py from design/brand. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            '    <path android:fillColor="%s" android:fillType="evenOdd" android:pathData="%s" />\n</vector>\n') % (comment, fill, path)


def svg_tile():
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">\n'
            '  <defs><linearGradient id="g" x1="0" y1="0" x2=".35" y2="1"><stop offset="0" stop-color="#2c2c33"/>'
            '<stop offset=".75" stop-color="#0d0d10"/></linearGradient></defs>\n'
            '  <rect width="100" height="100" rx="22" fill="url(#g)"/>\n'
            '  <path transform="translate(17 17) scale(.66)" fill="#f5f5f6" fill-rule="evenodd" d="%s"/>\n</svg>\n') % MARK_DATA


def main():
    pack = ROOT / "desktop/app/packaging"
    tile(512, 0.22).save(pack / "reflux.png", optimize=True)
    (pack / "reflux.ico").write_bytes(ico([tile(s, 0.22) for s in (16, 24, 32, 48, 64, 128, 256)]))
    res = ROOT / "android/app/src/main/res"
    (res / "drawable/ic_launcher_foreground.xml").write_text(vector("#FFF5F5F6", "The Reflux mark, inside the safe zone of an adaptive icon."), encoding="utf-8", newline="\n")
    (res / "drawable/ic_launcher_monochrome.xml").write_text(vector("#FFFFFFFF", "The mark alone, for themed icons: the system tints it."), encoding="utf-8", newline="\n")
    banner((320, 180), 0.70).save(res / "drawable-xhdpi/tv_banner.png", optimize=True)
    (ROOT / "desktop/app/src/main/resources").mkdir(parents=True, exist_ok=True)
    (ROOT / "desktop/app/src/main/resources/reflux-mark.path").write_text(MARK_DATA + "\n", encoding="utf-8", newline="\n")

    web = ROOT / "website/public"
    (web / "favicon.svg").write_text(svg_tile(), encoding="utf-8", newline="\n")
    for name in ("reflux-mark.svg", "reflux-lockup.svg"):
        (web / name.replace("reflux-", "")).write_text((BRAND / name).read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    tile(32, 0.22).save(web / "favicon-32.png", optimize=True)
    tile(180).save(web / "apple-touch-icon.png", optimize=True)
    tile(192, 0.22).save(web / "icon-192.png", optimize=True)
    tile(512, 0.22).save(web / "icon-512.png", optimize=True)
    banner((1200, 630), 0.48).save(web / "og-image.png", optimize=True)
    old = web / "icon.png"
    if old.exists():
        old.unlink()

    store = BRAND / "store"
    store.mkdir(exist_ok=True)
    tile(512).save(store / "play-icon-512.png", optimize=True)              # Play masks it itself: full bleed
    banner((1024, 500), 0.52).save(store / "play-feature-graphic-1024x500.png", optimize=True)
    banner((1280, 720), 0.50).save(store / "play-tv-banner-1280x720.png", optimize=True)
    tile(512).save(store / "amazon-icon-512.png", optimize=True)
    tile(114).save(store / "amazon-icon-114.png", optimize=True)
    banner((1280, 720), 0.50).save(store / "amazon-firetv-icon-1280x720.png", optimize=True)
    banner((1920, 1080), 0.40).save(store / "amazon-firetv-background-1920x1080.png", optimize=True)
    print("brand assets written")


if __name__ == "__main__":
    main()
